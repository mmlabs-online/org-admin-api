    ROLE_CREATED = "role.created"
    ROLE_UPDATED = "role.updated"
    ROLE_DELETED = "role.deleted"
    ROLE_PERMISSIONS_REPLACED = "role.permissions_replaced"
    ROLE_ASSIGNMENT_GRANTED = "role_assignment.granted"
