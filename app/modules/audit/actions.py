"""The audit catalogue (ADM-004): one `AuditAction` per state change, past tense."""

from enum import StrEnum


class ActorKind(StrEnum):
    USER = "user"
    SYSTEM = "system"
    ANONYMOUS = "anonymous"  # an unauthenticated caller: failed logins, cookie-only events


class AuditOutcome(StrEnum):
    SUCCESS = "success"
    FAILURE = "failure"
    DENIED = "denied"


class AuditTarget(StrEnum):
    ORGANIZATION = "organization"
    USER = "user"
    APP = "app"
    PERMISSION = "permission"
    ROLE = "role"
    ROLE_ASSIGNMENT = "role_assignment"
    DEVICE_SESSION = "device_session"
    INVITATION = "invitation"
    APP_CREDENTIAL = "app_credential"
    DEPLOYER_CREDENTIAL = "deployer_credential"
    JOIN_REQUEST = "join_request"
    ENTITLEMENT = "entitlement"
    BUG_REPORT = "bug_report"
    RELEASE = "release"
    USAGE_METRIC = "usage_metric"


